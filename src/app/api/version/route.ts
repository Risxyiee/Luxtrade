import { NextResponse } from 'next/server'

// ══════════════════════════════════════════════════════════════════════════
// Fingerprint build produksi — /api/version
// Bump VERSION setiap rilis penting. Dipakai untuk membuktikan pipeline
// deploy (Workers Builds / GitHub Actions) benar-benar mengirim kode
// terbaru ke Cloudflare: kalau endpoint ini 404 / versi lama → build
// produksi tidak jalan.
// ══════════════════════════════════════════════════════════════════════════

export const dynamic = 'force-dynamic'

const VERSION = '2026-11-11.4'
const NOTES = 'ROADMAP #4: Panel LAPORAN KPI KARYAWAN di kantor 3D (/kantor-ceo) — angka nyata per karyawan AI (artikel terbit Farhan, video TikTok + views Sinta, draf ACC Bagas/Maya, MRR Putri, akademi harian) dihitung langsung dari database, tanpa LLM.'

export async function GET() {
  return NextResponse.json(
    {
      version: VERSION,
      notes: NOTES,
      time: new Date().toISOString(),
    },
    { headers: { 'Cache-Control': 'no-store' } }
  )
}
