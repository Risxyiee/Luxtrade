-- 1) Pastikan tabel ada (no-op kalau sudah ada) — skema dasar.
CREATE TABLE IF NOT EXISTS public.pine_alert_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid,
  script_id   text,
  symbol      text,
  signal_type text,
  bar_time    timestamptz,
  price       double precision,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- 2) Self-healing kolom (no-op utk kolom yang sudah ada dgn tipe lain).
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS user_id     uuid;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS script_id   text;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS symbol      text;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS signal_type text;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS bar_time    timestamptz;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS price       double precision;
ALTER TABLE public.pine_alert_log ADD COLUMN IF NOT EXISTS created_at  timestamptz DEFAULT now();

-- 3) Hapus duplikat lama SEBELUM bikin unique index (kalau tidak,
--    CREATE UNIQUE INDEX bisa gagal kalau ada duplikat historis).
--    Simpan baris TERAWAL (id terkecil) per kunci dedupe.
DELETE FROM public.pine_alert_log a
USING public.pine_alert_log b
WHERE a.id > b.id
  AND a.user_id     IS NOT DISTINCT FROM b.user_id
  AND a.script_id   IS NOT DISTINCT FROM b.script_id
  AND a.symbol      IS NOT DISTINCT FROM b.symbol
  AND a.signal_type IS NOT DISTINCT FROM b.signal_type
  AND a.bar_time    IS NOT DISTINCT FROM b.bar_time;

-- 4) Unique index dedupe — TARGET ON CONFLICT kode:
--    onConflict: 'user_id,script_id,symbol,signal_type,bar_time'
CREATE UNIQUE INDEX IF NOT EXISTS pine_alert_log_dedupe_uidx
  ON public.pine_alert_log (user_id, script_id, symbol, signal_type, bar_time);

-- 5) Keamanan setara tabel lain: RLS aktif TANPA policy = deny-all
--    utk anon/authenticated; service_role bypass + GRANT ALL sudah
--    dicakup migrasi 019 (ALL TABLES IN SCHEMA public).
ALTER TABLE public.pine_alert_log ENABLE ROW LEVEL SECURITY;
