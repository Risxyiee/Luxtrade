-- ============================================================
-- MIGRASI 025 — profiles: FINALISASI GRANTS (REVOKE sisa DDL)
-- ============================================================
-- Konteks:
--   Migrasi 024 (sudah dijalankan Bos ✅) menutup INSERT/UPDATE/DELETE
--   dari authenticated & anon.
--
--   VERIFIKASI-2 Bos menunjukkan kondisi policies SUDAH SEHAT:
--   - RLS profiles SUDAH ON (rls_on = true)
--   - Semua policy owner-scoped (auth.uid()::text = id):
--       "Users can view own profile"   SELECT
--       "Users can insert own profile" INSERT
--       "Users can update own profile" UPDATE
--       "Users can delete own profile" DELETE
--       "Service role full access"     ALL (service_role)
--   → TIDAK perlu policy baru. Policy INSERT/UPDATE/DELETE own yang lama
--     otomatis jadi "surat mati" karena privilege-nya sudah dicabut
--     (policy tanpa privilege tidak pernah menyala) — dibiarkan saja
--     (prinsip: kalau ragu gausah dihapus).
--
--   Yang masih tersisa dari output verifikasi Bos: authenticated masih
--   memegang REFERENCES, TRIGGER, TRUNCATE. Ketiganya privilege
--   DDL/administratif yang TIDAK PERNAH bisa dipanggil lewat Supabase
--   JS / PostgREST — dicabut murni untuk hygiene (nol dampak app).
--
-- EKSEKUSI: Supabase Dashboard → SQL Editor → Run. (Bos)
-- Idempotent: aman dijalankan berulang.

REVOKE REFERENCES, TRIGGER, TRUNCATE ON TABLE public.profiles FROM authenticated;
REVOKE ALL ON TABLE public.profiles FROM anon;

